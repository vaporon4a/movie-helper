package clubreminder

import "fmt"

func Fallback(intent, tone string) Text {
	leads := map[string]string{
		"friendly":  "🎬 Давайте понемногу выбирать фильм для следующего киноклуба.",
		"dramatic":  "🎬 Где-то ждёт фильм, после которого нам захочется спорить до ночи. Пора его найти.",
		"sarcastic": "🎬 Объявляется спасательная операция: достать фильм из бесконечного списка «когда-нибудь посмотрим».",
		"profane":   "🍿 Ну что, пора уже выбрать кино, а не бесконечно откладывать это дело к чёртовой матери.",
		"roast":     "🍿 Киноклуб великих откладывателей, тащите варианты, ленивые засранцы. Наша нерешительность уже заслужила собственную экранизацию.",
	}
	body := "Может, вам недавно посоветовали интересную картину, попался цепляющий трейлер или вспомнился фильм, который давно хочется обсудить с компанией. Необязательно сразу искать единственный идеальный вариант: начнём с нескольких идей и посмотрим, что откликнется остальным.\n\nКидайте название в чат и пару слов, чем он заинтересовал. Если названия пока нет, начните с настроения: хочется посмеяться, понервничать, удивиться или после титров ещё немного поспорить. Из этого тоже получится хороший выбор."
	if intent == Discuss {
		body = "Вернёмся к обсуждению вариантов для следующего киноклуба. Желания меняются: то тянет на лёгкую комедию, то хочется напряжённой истории или чего-нибудь совсем странного. Не надо держаться за прошлое настроение только потому, что мы уже успели его озвучить.\n\nКакие фильмы вам сейчас интереснее? Можно принести новую находку, поддержать понравившуюся идею или объяснить, какого кино хочется на этот раз. Кидайте в чат названия и пару слов о своём выборе — пусть обсуждение поможет нам собраться вокруг фильма, который действительно хочется посмотреть вместе."
	}
	return Text{Body: fmt.Sprintf("%s\n\n%s", leads[tone], body), Intent: intent, Tone: tone, Provider: "template"}
}

// FallbackForUsage rotates tone without changing a persisted retry snapshot.
func FallbackForUsage(intent string, uses int) Text { return Fallback(intent, Tones[uses%len(Tones)]) }
